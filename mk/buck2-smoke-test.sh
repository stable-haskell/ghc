#!/bin/sh
# Smoke test of a GHC installation built with buck2 (see README.md,
# "Building with Buck2"): the store directory of //buck2-ghc:stage2-libdir
# (bin/ghc, bin/ghc-pkg, ...). Compiles and runs small programs that use
# the libraries, the threaded RTS, Template Haskell, the FFI, hsc2hs and
# runghc.
#
#   mk/buck2-smoke-test.sh $(buck2 build //buck2-ghc:stage2-libdir -m opt --show-simple-output)
set -eu

if [ "$#" -ne 1 ]; then
  echo "usage: $0 <stage2-store>" >&2
  exit 1
fi
# Do not let an environment file provide libraries missing from the store.
export GHC_ENVIRONMENT=-
store=$(realpath "$1")
ghc="$store/bin/ghc"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"

# Keep the program's exit status as well as its output: a pipe to grep,
# or a command substitution inside test, can hide a failing program.
expect_output() (
  expected=$1
  shift
  actual=$("$@")
  test "$actual" = "$expected"
)

echo "== $ghc --version"
"$ghc" --version
packages=$("$store/bin/ghc-pkg" list --simple-output)
printf '%s\n' "$packages" | awk '{ print "packages: " NF }'
"$store/bin/ghc-pkg" check

echo "== a program with containers, directory and text"
cat > Hello.hs <<'HS'
module Main where
import qualified Data.Map as M
import qualified Data.Text as T
import System.Directory (getCurrentDirectory)
main :: IO ()
main = do
  d <- getCurrentDirectory
  putStrLn (T.unpack (T.toUpper (T.pack "hello")) ++ " " ++ show (M.toList (M.fromList [(1 :: Int, "a")])) ++ " " ++ show (not (null d)))
HS
"$ghc" -O Hello.hs -o hello
expect_output 'HELLO [(1,"a")] True' ./hello

echo "== the threaded RTS"
"$ghc" -O -threaded Hello.hs -o hello-thr -fforce-recomp
expect_output 'HELLO [(1,"a")] True' ./hello-thr +RTS -N2 -RTS

echo "== Template Haskell (the internal interpreter)"
cat > TH.hs <<'HS'
{-# LANGUAGE TemplateHaskell #-}
module Main where
import Language.Haskell.TH
main :: IO ()
main = print $(litE (integerL (sum [1 .. 10])))
HS
"$ghc" TH.hs -o th
expect_output 55 ./th

echo "== Template Haskell (the installed external interpreter)"
"$ghc" TH.hs -fexternal-interpreter -fforce-recomp -o th-external
expect_output 55 ./th-external

echo "== the FFI"
cat > cbits.c <<'C'
int twice(int x) { return 2 * x; }
C
cat > FFI.hs <<'HS'
{-# LANGUAGE ForeignFunctionInterface #-}
module Main where
import Foreign.C.Types (CInt(..))
foreign import ccall "twice" c_twice :: CInt -> CInt
main :: IO ()
main = print (c_twice 21)
HS
"$ghc" FFI.hs cbits.c -o ffi
expect_output 42 ./ffi

echo "== hsc2hs"
cat > Hsc.hsc <<'HS'
module Main where
#include <limits.h>
main :: IO ()
main = print ((#const CHAR_BIT) :: Int)
HS
"$store/bin/hsc2hs" Hsc.hsc -o Hsc.hs
"$ghc" Hsc.hs -o hsc
expect_output 8 ./hsc

echo "== ghc -e and runghc"
expect_output 120 "$ghc" -e 'product [1 .. 5 :: Int]'
expect_output 'HELLO [(1,"a")] True' "$store/bin/runghc" Hello.hs

echo "== runghc uses the installed compiler and package database"
compiler_version=$("$ghc" --numeric-version)
ghc_libdir=$("$ghc" --print-libdir)
"$store/bin/runghc" -v Hello.hs > runghc.out 2> runghc.log
grep -Fx 'HELLO [(1,"a")] True' runghc.out
grep -F "Glasgow Haskell Compiler, Version $compiler_version," runghc.log
grep -F "loading package database $ghc_libdir/package.conf.d" runghc.log

echo "== haddock uses the installed GHC and auxiliary files"
expect_output "$ghc_libdir" "$store/bin/haddock" --print-ghc-libdir
cat > Buck2Doc.hs <<'HS'
-- | Documentation generated by the installed Haddock.
module Buck2Doc (answer) where
-- | The answer.
answer :: Int
answer = 42
HS
"$store/bin/haddock" --html --odir docs Buck2Doc.hs
test -s docs/Buck2Doc.html
test -s docs/index.html
test -s docs/haddock-bundle.min.js
test -s docs/quick-jump.css

echo "== hpc runs"
"$store/bin/hpc" version

echo "buck2 smoke test: OK"
