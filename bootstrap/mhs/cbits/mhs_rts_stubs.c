/* MicroHs stage1 RTS stubs.
 *
 * Linked into stage1 binaries compiled with MicroHs (mhs), which has no
 * GHC RTS.  Covers every C symbol the stage1 Haskell closure references
 * via `foreign import` that the real RTS (or compiler/cbits) would
 * otherwise provide.
 *
 * Symbols covered here:
 *   ghc_unique_counter64 / ghc_unique_inc
 *     Address-of imports in compiler/GHC/Types/Unique/Supply.hs.
 *     Types mirror rts/Globals.c: HsWord64 counter, HsInt increment.
 *     MicroHs maps Haskell Int to intptr_t (see mhs HsFFI.h).
 *   rts_isProfiled / rts_isDynamic / rts_isThreaded / rts_isDebugged /
 *   rts_isTracing
 *     Pure queries in compiler/GHC/Platform/Ways.hs.  The single-image
 *     stage1 binary is always static, unprofiled, unthreaded, undebugged
 *     and untraced, so all report 0.
 *   getOrSetLibHSghcGlobalHasPprDebug / getOrSetLibHSghcGlobalHasNoDebugOutput
 *   / getOrSetLibHSghcGlobalHasNoStateHack
 *     Shared-CAF accessors generated by the SHARED_GLOBAL_VAR macros in
 *     compiler/GHC/Utils/GlobalVars.hs.  With one image there is nothing
 *     to share across, so the identity function is exact.
 *   isFloatNaN / isFloatInfinite / isFloatDenormalized / isFloatNegativeZero /
 *   isFloatFinite and the isDouble* counterparts, rintFloat / rintDouble,
 *   __int_encodeDouble / __word_encodeDouble
 *     `foreign import ccall` targets in libraries/ghc-internal
 *     (GHC.Internal.Float, GHC.Internal.Float.RealFracMethods,
 *     GHC.Internal.Bignum.Primitives).  Curated C11 (<math.h>) ports of
 *     rts/StgPrimFloat.c and libraries/ghc-internal/cbits/primFloat.c.
 *
 * Deliberately NOT provided here (no C symbol is linked under __MHS__):
 *   setHeapSize / enableTimingStats
 *     Haskell no-ops in compiler/GHC/Driver/Session.hs.
 *   keepCAFsForGHCi
 *     Haskell `return True` in compiler/GHC.hs.
 *   rename
 *     libc provides it; used by the __MHS__ branch of
 *     libraries/ghc-boot/GHC/Unit/Database.hs.
 *   getOrSetLibHSghcFastStringTable
 *     Only referenced from the non-__MHS__ branch of
 *     compiler/GHC/Data/FastString.hs.
 *   ZSTD_compress / ZSTD_compressBound
 *     Only referenced when HAVE_LIBZSTD is defined, which the mhs
 *     stage1 build never defines.
 *   _getpid / _close / _get_osfhandle / GetConsoleMode / SetConsoleMode
 *     Only referenced from mingw32_HOST_OS branches.
 *
 * This file replaces compiler/cbits/genSym.c, compiler/cbits/cutils.c and
 * compiler/cbits/keepCAFsForGHCi.c for the mhs stage1 link: with the
 * HAVE_UNIQUE64 RTS those cbits define no unique counter themselves, and
 * the cutils/keepCAFs objects need real RTS headers (Rts.h) that the mhs
 * stage1 build does not configure.
 */

#include <math.h>
#include <stddef.h>
#include <stdint.h>

#include "mhs_rts_stubs.h"

/* Unique supply counter (compiler/GHC/Types/Unique/Supply.hs). */
uint64_t ghc_unique_counter64 = 0;
intptr_t ghc_unique_inc = 1;

/* RTS way queries (compiler/GHC/Platform/Ways.hs). */
intptr_t rts_isProfiled(void) { return 0; }
intptr_t rts_isDynamic(void) { return 0; }
intptr_t rts_isThreaded(void) { return 0; }
intptr_t rts_isDebugged(void) { return 0; }
intptr_t rts_isTracing(void) { return 0; }

/* Shared-global accessors (compiler/GHC/Utils/GlobalVars.hs). */
void *getOrSetLibHSghcGlobalHasPprDebug(void *p) { return p; }
void *getOrSetLibHSghcGlobalHasNoDebugOutput(void *p) { return p; }
void *getOrSetLibHSghcGlobalHasNoStateHack(void *p) { return p; }

/* IEEE-754 predicates (libraries/ghc-internal/src/GHC/Internal/Float.hs).
 * Semantics mirror rts/StgPrimFloat.c and libraries/ghc-internal/cbits/primFloat.c:
 * C11 math.h classification (isnan/isinf/isfinite/fpclassify/signbit) is
 * exactly the bit-level IEEE-754 test the RTS performs. */
intptr_t isFloatNaN(float f) { return isnan(f) ? 1 : 0; }
intptr_t isFloatInfinite(float f) { return isinf(f) ? 1 : 0; }
intptr_t isFloatDenormalized(float f) { return fpclassify(f) == FP_SUBNORMAL ? 1 : 0; }
intptr_t isFloatNegativeZero(float f) { return (f == 0.0f && signbit(f)) ? 1 : 0; }
intptr_t isFloatFinite(float f) { return isfinite(f) ? 1 : 0; }

intptr_t isDoubleNaN(double d) { return isnan(d) ? 1 : 0; }
intptr_t isDoubleInfinite(double d) { return isinf(d) ? 1 : 0; }
intptr_t isDoubleDenormalized(double d) { return fpclassify(d) == FP_SUBNORMAL ? 1 : 0; }
intptr_t isDoubleNegativeZero(double d) { return (d == 0.0 && signbit(d)) ? 1 : 0; }
intptr_t isDoubleFinite(double d) { return isfinite(d) ? 1 : 0; }

/* Round to nearest, ties to even (libraries/ghc-internal/src/GHC/Internal/
 * Float/RealFracMethods.hs c_rintDouble/c_rintFloat).
 * C rint() rounds per the current rounding mode, which is to-nearest-even
 * by default: exactly the semantics of GHC's primFloat.c implementation,
 * used only for round-to-Integral. */
double rintDouble(double d) { return rint(d); }
float rintFloat(float f) { return rintf(f); }

/* Small-Integer to Double conversion (rts/StgPrimFloat.c).
 * Mirror the RTS: scale the magnitude with ldexp, then apply the sign.
 * The unsigned negation avoids signed overflow for INT64_MIN. */
double __int_encodeDouble(int64_t j, intptr_t e)
{
  uint64_t mag = (j < 0) ? -(uint64_t)j : (uint64_t)j;
  double r = (double)mag;
  if (r != 0.0)
    r = ldexp(r, (int)e);
  return (j < 0) ? -r : r;
}

double __word_encodeDouble(uint64_t j, intptr_t e)
{
  double r = (double)j;
  if (r != 0.0)
    r = ldexp(r, (int)e);
  return r;
}
