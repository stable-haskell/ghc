void freePreloadObjectFile_PEi386(ObjectCode *oc)
{
    if (oc->image) {
        LL_FREE_FOR(oc->L, oc->image);
        oc->image = NULL;
    }

    if (oc->coff_info) {
        /* Release the unwinder information.
           See Note [Exception Unwinding].  */
        if (oc->coff_info->pdata) {
            ll_pe_host_unregister_unwind(oc);
            oc->coff_info->xdata = NULL;
            oc->coff_info->pdata = NULL;
        }

        /* Failed or never-started initialization still owns pending lists.
         * Successful init/fini execution has already cleared its list. */
        freeInitFiniList(oc->L, oc->coff_info->init);
        freeInitFiniList(oc->L, oc->coff_info->fini);
        oc->coff_info->init = NULL;
        oc->coff_info->fini = NULL;
        if (oc->coff_info->ch_info) {
           LL_FREE_FOR(oc->L, oc->coff_info->ch_info);
        }
        LL_FREE_FOR(oc->L, oc->coff_info);
        oc->coff_info = NULL;
    }
}

// Free oc->info and oc->sections[i]->info.
static void releaseOcInfo(ObjectCode* oc) {
    if (!oc) return;

    if (oc->coff_info) {
        freeInitFiniList(oc->L, oc->coff_info->init);
        freeInitFiniList(oc->L, oc->coff_info->fini);
        LL_FREE_FOR(oc->L, oc->coff_info->ch_info);
        LL_FREE_FOR(oc->L, oc->coff_info->symbols);
        LL_FREE_FOR(oc->L, oc->coff_info->str_tab);
        oc->coff_info->init = NULL;
        oc->coff_info->fini = NULL;
        oc->coff_info->ch_info = NULL;
        oc->coff_info->symbols = NULL;
        oc->coff_info->str_tab = NULL;
        /* Failed resolution can follow exception-table registration. Keep
         * its record until physical disposal unregisters the live table. */
        if (oc->coff_info->pdata == NULL) {
            LL_FREE_FOR(oc->L, oc->coff_info);
            oc->coff_info = NULL;
        }
    }
    for (int i = 0; i < oc->n_sections; i++){
        Section *section = &oc->sections[i];
        if (section->coff_info) {
            LL_FREE_FOR(oc->L, section->coff_info->name);
            if (section->coff_info->relocs) {
                LL_FREE_FOR(oc->L, section->coff_info->relocs);
                section->coff_info->relocs = NULL;
            }
            LL_FREE_FOR(oc->L, section->coff_info);
            section->coff_info = NULL;
        }
    }
}

/*************
 * This function determines what kind of COFF image we are dealing with.
 * This is needed in order to correctly load and verify objects and their
 * sections.
 *************/
COFF_OBJ_TYPE getObjectType ( ll_linker *L, char* image, pathchar* fileName )
{
    /* {D1BAA1C7-BAEE-4ba9-AF20-FAF66AA4DCB8} */
    static const char header_bigobj_classid[16] =
    {
      0xC7, 0xA1, 0xBA, 0xD1,
      0xEE, 0xBA,
      0xa9, 0x4b,
      0xAF, 0x20,
      0xFA, 0xF6, 0x6A, 0xA4, 0xDC, 0xB8
    };

    uint16_t machine;
    COFF_OBJ_TYPE ret = COFF_UNKNOWN;
    /* First check if we have an ANON_OBJECT_HEADER signature.  */
    ll_coff_anon_header* anon = (ll_coff_anon_header*)image;
    if (   anon->Sig1 == LL_COFF_IMAGE_FILE_MACHINE_UNKNOWN
        && anon->Sig2 == LL_COFF_IMPORT_OBJECT_HDR_SIG2)
    {
        machine = anon->Machine;
        if (verifyCOFFHeader (L, machine, NULL, fileName))
        {
            switch (anon->Version)
            {
                case 0:
                    ret = COFF_IMPORT_LIB;
                    break;
                case 1:
                    ret = COFF_ANON_OBJ;
                    break;
                case 2:
                    if (memcmp (&anon->ClassID, header_bigobj_classid, 16) == 0)
                        ret = COFF_ANON_BIG_OBJ;
                    break;
                default:
                    break;
            }
        }
    } else {
        /* If it's not an ANON_OBJECT then try an image file.  */
        ll_coff_file_header* img = (ll_coff_file_header*)image;
        machine = img->Machine;
        if (verifyCOFFHeader (L, machine, img, fileName))
            ret = COFF_IMAGE;
    }
    return ret;
}

/*************
 * Retrieve common header information
 *************/
COFF_HEADER_INFO* getHeaderInfo ( ObjectCode* oc )
{
   COFF_OBJ_TYPE coff_type = getObjectType (oc->L, oc->image, OC_INFORMATIVE_FILENAME(oc));

   COFF_HEADER_INFO* info
     = LL_MALLOC_FOR(oc->L, sizeof(COFF_HEADER_INFO), "getHeaderInfo");
   memset (info, 0, sizeof(COFF_HEADER_INFO));
   info->type = coff_type;
   switch (coff_type)
   {
       case COFF_IMAGE:
        {
         ll_coff_file_header* hdr = (ll_coff_file_header*)oc->image;
         info->sizeOfHeader         = sizeof(ll_coff_file_header);
         info->sizeOfOptionalHeader = hdr->SizeOfOptionalHeader;
         info->pointerToSymbolTable = hdr->PointerToSymbolTable;
         info->numberOfSymbols      = hdr->NumberOfSymbols;
         info->numberOfSections     = hdr->NumberOfSections;
        }
        break;
       case COFF_ANON_BIG_OBJ:
        {
         ll_coff_bigobj_header* hdr = (ll_coff_bigobj_header*)oc->image;
         info->sizeOfHeader         = sizeof(ll_coff_bigobj_header);
         info->sizeOfOptionalHeader = 0;
         info->pointerToSymbolTable = hdr->PointerToSymbolTable;
         info->numberOfSymbols      = hdr->NumberOfSymbols;
         info->numberOfSections     = hdr->NumberOfSections;
        }
        break;
       default:
        {
         LL_FREE_FOR(oc->L, info);
         info = NULL;
         LL_LOG_ERROR_FOR(oc->L, "Unknown COFF %d type in getHeaderInfo.", coff_type);
        }
        break;
   }

   return info;
}

